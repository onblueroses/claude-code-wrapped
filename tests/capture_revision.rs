static NEXT_SCRATCH_ID: AtomicU64 = AtomicU64::new(0);

struct ScratchDir(PathBuf);

impl ScratchDir {
    fn new() -> Self {
        let nonce = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .expect("clock before epoch")
            .as_nanos();
        let scratch_id = NEXT_SCRATCH_ID.fetch_add(1, Ordering::Relaxed);
        let path = std::env::temp_dir().join(format!(
            "ccwrapped-capture-revision-{}-{nonce}-{scratch_id}",
            std::process::id()
        ));
        fs::create_dir_all(&path).expect("create scratch directory");
        Self(path)
    }

    fn path(&self) -> &std::path::Path {
        &self.0
    }
}

fn run_git(root: &std::path::Path, args: &[&str]) -> String {
    let output = Command::new("git")
        .args(args)
        .current_dir(root)
        .output()
        .expect("run git");
    assert!(
        output.status.success(),
        "git {args:?} failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    String::from_utf8(output.stdout)
        .expect("git output is UTF-8")
        .trim()
        .to_owned()
}

fn initialize_product_checkout(root: &std::path::Path) -> String {
    fs::create_dir_all(root.join("src")).expect("create product source");
    fs::create_dir_all(root.join("scripts")).expect("create scripts directory");
    fs::create_dir_all(root.join("examples")).expect("create examples directory");
    fs::write(
        root.join("Cargo.toml"),
        "[package]\nname = \"claude-code-wrapped\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n[lib]\nname = \"ccwrapped\"\n",
    )
    .expect("write manifest");
    fs::write(
        root.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = \"claude-code-wrapped\"\nversion = \"0.0.0\"\n",
    )
    .expect("write lockfile");
    fs::write(root.join("src/lib.rs"), "pub fn baseline() {}\n").expect("write source");
    fs::write(root.join("src/report.rs"), "").expect("write empty report audit source");
    fs::write(
        root.join("examples/capture_report_schema.rs"),
        "fn main() {}\n",
    )
    .expect("write report schema example");
    for script in [
        "scripts/capture-report-schema.sh",
        "scripts/capture-public-api.sh",
    ] {
        fs::copy(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(script),
            root.join(script),
        )
        .expect("copy capture script");
    }
    let audit_root = root.join("tests/support/report-source-audit");
    fs::create_dir_all(audit_root.join("src")).expect("create source audit directory");
    for relative in ["Cargo.toml", "Cargo.lock", "src/main.rs"] {
        fs::copy(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("tests/support/report-source-audit")
                .join(relative),
            audit_root.join(relative),
        )
        .expect("copy report source audit input");
    }

    run_git(root, &["init", "--quiet"]);
    run_git(root, &["config", "user.name", "Capture Test"]);
    run_git(root, &["config", "user.email", "capture@example.invalid"]);
    run_git(root, &["config", "core.autocrlf", "false"]);
    run_git(root, &["config", "core.hooksPath", "no-hooks"]);
    run_git(root, &["add", "Cargo.toml", "Cargo.lock", "src"]);
    run_git(root, &["commit", "--quiet", "-m", "baseline"]);
    run_git(root, &["rev-parse", "HEAD"])
}

fn padded_source(function: &str, value: &str) -> String {
    let mut source = format!("pub fn {function}() -> &'static str {{ \"{value}\" }}\n");
    for index in 0..20_000 {
        source.push_str(&format!("fn capture_padding_{index}() {{}}\n"));
    }
    source
}

fn capture_while_mutating_live_source(
    script: &str,
    initial_source: &str,
    mutated_source: &str,
    example_source: &str,
) -> String {
    let scratch = ScratchDir::new();
    initialize_product_checkout(scratch.path());
    fs::write(scratch.path().join("src/lib.rs"), initial_source).expect("write initial source");
    fs::write(
        scratch.path().join("examples/capture_report_schema.rs"),
        example_source,
    )
    .expect("write capture example");
    run_git(scratch.path(), &["add", "src/lib.rs"]);
    run_git(
        scratch.path(),
        &["commit", "--quiet", "-m", "add mutation fixture"],
    );
    let head = run_git(scratch.path(), &["rev-parse", "HEAD"]);
    let output_path = scratch.path().join("capture.txt");

    let mut child = Command::new("bash")
        .arg(script)
        .arg(&output_path)
        .current_dir(scratch.path())
        .env("CCWRAPPED_CAPTURE_REVISION", head)
        .stdout(Stdio::null())
        .stderr(Stdio::piped())
        .spawn()
        .expect("start capture for concurrent-mutation regression");
    let mut stderr = BufReader::new(child.stderr.take().expect("capture child stderr"));
    let mut transcript = String::new();
    loop {
        let mut line = String::new();
        let bytes = stderr.read_line(&mut line).expect("read capture progress");
        assert_ne!(
            bytes, 0,
            "capture exited before its compiler phase:\n{transcript}"
        );
        transcript.push_str(&line);
        if line.contains("Checking claude-code-wrapped") {
            break;
        }
    }

    fs::write(scratch.path().join("src/lib.rs"), mutated_source)
        .expect("mutate live source during capture");
    stderr
        .read_to_string(&mut transcript)
        .expect("read remaining capture progress");
    let status = child.wait().expect("wait for capture");
    assert!(status.success(), "snapshot capture failed:\n{transcript}");
    fs::read_to_string(output_path).expect("read snapshot capture artifact")
}

impl Drop for ScratchDir {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

#[test]
fn capture_scripts_default_to_current_artifacts_and_keep_baselines_guarded() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
    let public =
        fs::read_to_string(root.join("scripts/capture-public-api.sh")).expect("read API capture");
    let report = fs::read_to_string(root.join("scripts/capture-report-schema.sh"))
        .expect("read report capture");

    assert!(public.contains("output=${1:-\"$repo_root/docs/current/public-api-v0.3.0.txt\"}"));
    assert!(public.contains("default_output=\"$repo_root/docs/current/public-api-v0.3.0.txt\""));
    assert!(!public.contains("default_output=\"$repo_root/docs/baseline/public-api-v0.2.0.txt\""));
    assert!(report.contains("output=${1:-\"$repo_root/docs/current/report-v2-fields.txt\"}"));
    assert!(report.contains("default_output=\"$repo_root/docs/current/report-v2-fields.txt\""));
    assert!(!report.contains("default_output=\"$repo_root/docs/baseline/report-v1-fields.txt\""));
}

#[test]
fn capture_scripts_isolate_mid_capture_product_mutation() {
    let initial_public = padded_source("baseline_before", "before");
    let mutated_public = padded_source("baseline_after", "after");
    let public_artifact = capture_while_mutating_live_source(
        "scripts/capture-public-api.sh",
        &initial_public,
        &mutated_public,
        "fn main() {}\n",
    );
    assert!(public_artifact.contains("ccwrapped::baseline_before"));
    assert!(!public_artifact.contains("ccwrapped::baseline_after"));

    let initial_report = padded_source("baseline_value", "before");
    let mutated_report = padded_source("baseline_value", "after");
    let report_artifact = capture_while_mutating_live_source(
        "scripts/capture-report-schema.sh",
        &initial_report,
        &mutated_report,
        "fn main() { println!(\"{}\", ccwrapped::baseline_value()); }\n",
    );
    assert!(report_artifact.ends_with("before\n"));
    assert!(!report_artifact.ends_with("after\n"));
}

#[test]
fn capture_scripts_reject_gitless_mutation_during_snapshot() {
    for (script, output_name) in [
        ("scripts/capture-report-schema.sh", "report.txt"),
        ("scripts/capture-public-api.sh", "public.txt"),
    ] {
        let scratch = ScratchDir::new();
        let head = initialize_product_checkout(scratch.path());
        fs::write(
            scratch.path().join("snapshot-padding.bin"),
            vec![0x5a; 4 * 1024 * 1024],
        )
        .expect("write snapshot timing fixture");
        fs::remove_dir_all(scratch.path().join(".git")).expect("remove Git metadata");

        let mut child = Command::new("bash")
            .arg(script)
            .arg(output_name)
            .current_dir(scratch.path())
            .env("CCWRAPPED_CAPTURE_REVISION", &head)
            .stdout(Stdio::null())
            .stderr(Stdio::piped())
            .spawn()
            .expect("start Git-less capture");

        let keep_mutating = Arc::new(AtomicBool::new(true));
        let mutator_flag = Arc::clone(&keep_mutating);
        let source_path = scratch.path().join("src/lib.rs");
        let mutation_path = scratch.path().with_extension("atomic-mutation");
        let mutator = thread::spawn(move || {
            let mut revision = 0_u64;
            while mutator_flag.load(Ordering::Relaxed) {
                fs::write(
                    &mutation_path,
                    format!("pub fn snapshot_revision_{revision}() {{}}\n"),
                )
                .expect("write atomic mutation candidate");
                fs::rename(&mutation_path, &source_path)
                    .expect("replace live source during snapshot");
                revision = revision.wrapping_add(1);
            }
        });

        let mut stderr = String::new();
        child
            .stderr
            .take()
            .expect("capture child stderr")
            .read_to_string(&mut stderr)
            .expect("read Git-less capture stderr");
        let status = child.wait().expect("wait for Git-less capture");
        keep_mutating.store(false, Ordering::Relaxed);
        mutator.join().expect("join snapshot mutator");

        assert!(!status.success(), "{script} accepted a torn snapshot");
        assert!(
            stderr.contains("repository changed while its private snapshot was created"),
            "unexpected {script} error: {stderr}"
        );
    }
}

#[test]
fn capture_rejects_mutated_cached_dependency() {
    let scratch = ScratchDir::new();
    let head = initialize_product_checkout(scratch.path());
    fs::write(
        scratch.path().join("Cargo.toml"),
        "[package]\nname = \"claude-code-wrapped\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n[lib]\nname = \"ccwrapped\"\n\n[dependencies]\nserde = \"=1.0.228\"\n",
    )
    .expect("write dependency manifest");
    let lock = Command::new("cargo")
        .args(["generate-lockfile", "--offline"])
        .current_dir(scratch.path())
        .output()
        .expect("generate dependency lockfile");
    assert!(
        lock.status.success(),
        "lockfile generation failed: {}",
        String::from_utf8_lossy(&lock.stderr)
    );
    fs::remove_dir_all(scratch.path().join(".git")).expect("remove Git metadata");

    let canonical_cargo_home = std::env::var_os("CARGO_HOME")
        .map(PathBuf::from)
        .or_else(|| std::env::var_os("HOME").map(|home| PathBuf::from(home).join(".cargo")))
        .expect("locate canonical Cargo home");
    let canonical_registry = canonical_cargo_home.join("registry");
    let serde_source = fs::read_dir(canonical_registry.join("src"))
        .expect("read registry sources")
        .find_map(|entry| {
            let namespace = entry.ok()?.file_name();
            let candidate = canonical_registry
                .join("src")
                .join(&namespace)
                .join("serde-1.0.228");
            candidate.is_dir().then_some((namespace, candidate))
        })
        .expect("find cached serde source");
    let namespace = serde_source.0;

    let ambient_home = ScratchDir::new();
    fs::create_dir_all(ambient_home.path().join("registry/src").join(&namespace))
        .expect("create ambient source cache");
    std::os::unix::fs::symlink(
        canonical_registry.join("cache"),
        ambient_home.path().join("registry/cache"),
    )
    .expect("link registry archives");
    std::os::unix::fs::symlink(
        canonical_registry.join("index"),
        ambient_home.path().join("registry/index"),
    )
    .expect("link registry index");
    let copied = Command::new("cp")
        .args(["-a", "--"])
        .arg(&serde_source.1)
        .arg(ambient_home.path().join("registry/src").join(&namespace))
        .output()
        .expect("copy ambient serde source");
    assert!(
        copied.status.success(),
        "copy failed: {}",
        String::from_utf8_lossy(&copied.stderr)
    );
    fs::write(
        ambient_home
            .path()
            .join("registry/src")
            .join(&namespace)
            .join("serde-1.0.228/src/lib.rs"),
        "compile_error!(\"ambient unpacked dependency source was used\");\n",
    )
    .expect("corrupt ambient unpacked dependency source");

    for (script, output) in [
        ("scripts/capture-report-schema.sh", "isolated-report.txt"),
        ("scripts/capture-public-api.sh", "isolated-public.txt"),
    ] {
        let result = Command::new("bash")
            .arg(script)
            .arg(output)
            .current_dir(scratch.path())
            .env("CARGO_HOME", ambient_home.path())
            .env("CCWRAPPED_CAPTURE_REVISION", &head)
            .output()
            .expect("capture with mutated unpacked dependency cache");
        assert!(
            result.status.success(),
            "{script} used ambient unpacked source: {}",
            String::from_utf8_lossy(&result.stderr)
        );
        let artifact = fs::read_to_string(scratch.path().join(output)).expect("read artifact");
        assert!(artifact.contains("dependency-sources-sha256 "));
    }

    let corrupt_home = ScratchDir::new();
    let corrupt_cache = corrupt_home.path().join("registry/cache").join(&namespace);
    fs::create_dir_all(&corrupt_cache).expect("create corrupt archive cache");
    std::os::unix::fs::symlink(
        canonical_registry.join("index"),
        corrupt_home.path().join("registry/index"),
    )
    .expect("link registry index for corrupt archive");
    for archive in [
        "proc-macro2-1.0.106.crate",
        "quote-1.0.45.crate",
        "serde-1.0.228.crate",
        "serde_core-1.0.228.crate",
        "serde_derive-1.0.228.crate",
        "syn-2.0.117.crate",
        "unicode-ident-1.0.24.crate",
    ] {
        fs::copy(
            canonical_registry
                .join("cache")
                .join(&namespace)
                .join(archive),
            corrupt_cache.join(archive),
        )
        .unwrap_or_else(|error| panic!("copy {archive}: {error}"));
    }
    let serde_archive = corrupt_cache.join("serde-1.0.228.crate");
    let mut corrupted = fs::read(&serde_archive).expect("read serde archive");
    corrupted.extend_from_slice(b"corrupt-cache");
    fs::write(&serde_archive, corrupted).expect("corrupt registry archive");

    for (script, output) in [
        ("scripts/capture-report-schema.sh", "corrupt-report.txt"),
        ("scripts/capture-public-api.sh", "corrupt-public.txt"),
    ] {
        let result = Command::new("bash")
            .arg(script)
            .arg(output)
            .current_dir(scratch.path())
            .env("CARGO_HOME", corrupt_home.path())
            .env("CCWRAPPED_CAPTURE_REVISION", &head)
            .output()
            .expect("capture with corrupted registry archive");
        assert!(
            !result.status.success(),
            "{script} accepted a corrupt archive"
        );
        assert!(
            String::from_utf8_lossy(&result.stderr).contains("checksum"),
            "unexpected {script} error: {}",
            String::from_utf8_lossy(&result.stderr)
        );
    }
}

#[test]
