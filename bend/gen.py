#!/usr/bin/env python3
"""Generates the mechanical parts of the Bend engine.

bend/gen/line.bend   the flat per-line parse record, its setters and group resets
bend/gen/prices.bend the price table, from pricing/prices.tsv
bend/gen/assets.bend the stylesheets of the HTML formats, from bend/assets/, and the date of
                     the pricing page the price table was taken from

Run `python3 bend/gen.py` after changing either source; `--check` fails when the checked-in
output is stale.
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent

# (field, type, default) of the record one transcript line is parsed into.
LINE_FIELDS = [
    ("kind", "T.Rec", "T.KOther{}"),
    ("has_ts", "Bool", "False{}"),
    ("ts", "String", '""'),
    ("session", "String", '""'),
    ("cwd", "String", '""'),
    ("side", "Bool", "False{}"),
    ("meta", "Bool", "False{}"),
    ("has_uuid", "Bool", "False{}"),
    ("uuid", "String", '""'),
    ("has_mid", "Bool", "False{}"),
    ("mid", "String", '""'),
    ("model", "String", '""'),
    ("has_usage", "Bool", "False{}"),
    ("inp", "Nat", "0n"),
    ("out", "Nat", "0n"),
    ("cread", "Nat", "0n"),
    ("cwrite", "Nat", "0n"),
    ("c1h", "Nat", "0n"),
    ("c5m", "Nat", "0n"),
    ("ws", "Nat", "0n"),
    ("wf", "Nat", "0n"),
    ("fast", "Bool", "False{}"),
    ("geo", "Bool", "False{}"),
    ("human", "Bool", "False{}"),
    ("tools", "List<&2, T.Tool>", "Nil{}"),
    ("b_type", "T.BKind", "T.BOther{}"),
    ("b_has_id", "Bool", "False{}"),
    ("b_id", "String", '""'),
    ("b_name", "String", '""'),
    ("b_human", "Bool", "False{}"),
]

# A JSON value at one of these paths replaces everything below it, so a repeated key starts
# from defaults exactly as Python's json module keeps only the last occurrence.
GROUPS = {
    "usage": ["has_usage", "inp", "out", "cread", "cwrite", "c1h", "c5m", "ws", "wf", "fast", "geo"],
    "cc": ["c1h", "c5m"],
    "stu": ["ws", "wf"],
    "content": ["human", "tools"],
    "block": ["b_type", "b_has_id", "b_id", "b_name", "b_human"],
}
GROUPS["message"] = ["has_mid", "mid", "model"] + GROUPS["usage"] + GROUPS["content"]

HEADER = "# Generated by bend/gen.py; do not edit.\n\n"


def line_bend():
    names = [name for name, _, _ in LINE_FIELDS]
    fields = ", ".join(f"{name}: {typ}" for name, typ, _ in LINE_FIELDS)
    out = [HEADER, "import Base\nimport ../types.bend as T\n\n"]
    out.append("type Line is Data:\n")
    out.append(f"  Line{{{fields}}}\n\n")
    out.append("def Line.empty() -> Line:\n")
    out.append("  Line{" + ", ".join(default for _, _, default in LINE_FIELDS) + "}\n\n")
    for name, typ, _ in LINE_FIELDS:
        out.append(f"def Line.set_{name}(l: Line, v: {typ}) -> Line:\n")
        out.append("  match l:\n")
        out.append("    case Line{" + ", ".join("_" if n == name else n for n in names) + "}:\n")
        out.append("      Line{" + ", ".join("v" if n == name else n for n in names) + "}\n\n")
    for group, members in GROUPS.items():
        out.append(f"def Line.reset_{group}(l: Line) -> Line:\n")
        out.append("  match l:\n")
        out.append("    case Line{" + ", ".join("_" if n in members else n for n in names) + "}:\n")
        defaults = {name: default for name, _, default in LINE_FIELDS}
        out.append("      Line{" + ", ".join(defaults[n] if n in members else n for n in names) + "}\n\n")
    return "".join(out)


def prices_bend():
    rows = []
    for line in (REPO / "pricing" / "prices.tsv").read_text().splitlines():
        if line and not line.startswith("#"):
            model, speed, *values = line.split("\t")
            rows.append((model, speed == "fast", [int(v) for v in values]))
    out = [HEADER, "import Base\nimport ../types.bend as T\n\n"]
    out.append("# Microdollars per million tokens: input, 5m write, 1h write, cache read, output.\n")
    out.append("def Prices.table() -> List<&2, T.Price>:\n  [\n")
    for model, fast, values in rows:
        flag = "True{}" if fast else "False{}"
        out.append(f'    T.Price{{"{model}", {flag}, ' + ", ".join(f"{v}n" for v in values) + "},\n")
    out.append("  ]\n")
    return "".join(out)


def bend_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def prices_date():
    for line in (REPO / "pricing" / "prices.tsv").read_text().splitlines():
        if line.startswith("# Source: "):
            match = re.search(r"(\d{4}-\d{2}-\d{2})", line)
            if match:
                return match.group(1)
    sys.exit("pricing/prices.tsv names no dated source")


def assets_bend():
    out = [HEADER, "import Base\n\n"]
    for name in ("slides", "card"):
        lines = (HERE / "assets" / f"{name}.css").read_text().splitlines()
        out.append(f"def Css.{name}() -> String:\n  String.join([\n")
        out.extend(f"    {bend_string(line)},\n" for line in lines)
        out.append('  ], "\\n")\n\n')
    out.append("# The date of the pricing page pricing/prices.tsv was taken from.\n")
    out.append(f"def Prices.date() -> String:\n  {bend_string(prices_date())}\n")
    return "".join(out)


def main():
    outputs = {HERE / "gen" / "line.bend": line_bend(), HERE / "gen" / "prices.bend": prices_bend(), HERE / "gen" / "assets.bend": assets_bend()}
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
    if "--check" in sys.argv:
        for path in stale:
            print(f"stale: {path.relative_to(REPO)}", file=sys.stderr)
        sys.exit(1 if stale else 0)
    for path, text in outputs.items():
        path.parent.mkdir(exist_ok=True)
        path.write_text(text)


if __name__ == "__main__":
    main()
