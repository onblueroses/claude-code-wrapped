#!/usr/bin/env bash
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)
manifest=assets/README-ASSETS.sha256
required_chromium_version='Chromium 148.0.7778.178'
mode=${1:---verify-manifest}

cd "$repo_root"

verify_manifest() {
  sha256sum --check "$manifest"
}

if [[ $mode == --verify-manifest ]]; then
  verify_manifest
  exit 0
fi
if [[ $mode != --regenerate && $mode != --verify-render ]]; then
  printf 'usage: %s [--verify-manifest|--verify-render|--regenerate]\n' "$0" >&2
  exit 2
fi

if [[ -n ${CHROMIUM_BIN:-} ]]; then
  chromium_bin=$CHROMIUM_BIN
elif [[ -x /usr/lib/chromium/chromium ]]; then
  chromium_bin=/usr/lib/chromium/chromium
else
  chromium_bin=$(command -v chromium || command -v chromium-browser || true)
fi
if [[ -z $chromium_bin || ! -x $chromium_bin ]]; then
  printf 'README asset capture requires Chromium; set CHROMIUM_BIN to its executable.\n' >&2
  exit 1
fi
observed_chromium_version=$("$chromium_bin" --version | sed 's/[[:space:]]*$//')
if [[ $observed_chromium_version != "$required_chromium_version" &&
      ${CCWRAPPED_ALLOW_CHROMIUM_DRIFT:-0} != 1 ]]; then
  printf 'README asset capture requires %s; observed %s.\n' \
    "$required_chromium_version" "$observed_chromium_version" >&2
  printf 'Set CCWRAPPED_ALLOW_CHROMIUM_DRIFT=1 only for an intentional baseline refresh.\n' >&2
  exit 1
fi

temp_root=${TMPDIR:-/tmp}
scratch=$(mktemp -d "$temp_root/ccwrapped-readme-assets.XXXXXX")
profile_root=$(mktemp -d "$temp_root/ccwrapped-readme-chromium.XXXXXX")
trap 'rm -rf "$scratch" "$profile_root"' EXIT

if [[ -n ${CCWRAPPED_ASSET_BINARY:-} ]]; then
  ccwrapped_binary=$CCWRAPPED_ASSET_BINARY
  if [[ ! -x $ccwrapped_binary ]]; then
    printf 'CCWRAPPED_ASSET_BINARY is not executable: %s\n' "$ccwrapped_binary" >&2
    exit 1
  fi
else
  cargo build --locked --release
  ccwrapped_binary=$repo_root/target/release/ccwrapped
fi
mkdir -p "$scratch/output" "$scratch/home" "$scratch/claude" "$scratch/generated"
(
  cd "$scratch/output"
  HOME="$scratch/home" \
    CLAUDE_CONFIG_DIR="$scratch/claude" \
    NO_COLOR=1 \
    SOURCE_DATE_EPOCH=1784246400 \
    "$ccwrapped_binary" \
      --timezone UTC \
      --data-dir "$repo_root/tests/fixtures/readme-assets/projects" \
      --all \
      2026 >/dev/null
)

capture() {
  local output=$1
  local width=$2
  local height=$3
  local scale=$4
  local url=$5
  local virtual_time=${6:-0}
  local profile
  profile=$(mktemp -d "$profile_root/profile.XXXXXX")
  local chrome_args=(
    --headless
    --no-sandbox
    --disable-gpu
    --disable-extensions
    --disable-component-extensions-with-background-pages
    --disable-background-networking
    --disable-sync
    --metrics-recording-only
    --no-first-run
    --hide-scrollbars
    "--user-data-dir=$profile"
    "--window-size=$width,$height"
    "--force-device-scale-factor=$scale"
    "--screenshot=$scratch/generated/$output"
  )
  if (( virtual_time > 0 )); then
    chrome_args+=(
      --run-all-compositor-stages-before-draw
      "--virtual-time-budget=$virtual_time"
    )
  fi
  timeout 20s "$chromium_bin" "${chrome_args[@]}" "$url" >/dev/null 2>&1
  rm -rf "$profile"
}

report_url="file://$scratch/output/claude-code-wrapped.html"
capture hero-slide.png 1200 900 1 "$report_url#opening"
capture spend-slide.png 1200 900 1 "$report_url#api-equivalent"
capture cache-slide.png 1200 900 1 "$report_url#cache-evidence"
capture data-slide.png 1200 900 1 "$report_url#model-projects"
capture share-card.png 1080 1920 0.5 \
  "file://$scratch/output/claude-code-wrapped-card.html" 3000

assets=(
  hero-slide.png
  spend-slide.png
  cache-slide.png
  data-slide.png
  share-card.png
)

if [[ $mode == --verify-render ]]; then
  for asset in "${assets[@]}"; do
    cmp "$scratch/generated/$asset" "assets/$asset"
  done
  verify_manifest
  printf 'README assets reproduce byte-for-byte with %s.\n' "$observed_chromium_version"
  exit 0
fi

for asset in "${assets[@]}"; do
  install -m 0644 "$scratch/generated/$asset" "assets/$asset"
done

manifest_tmp=$(mktemp "$repo_root/assets/README-ASSETS.sha256.XXXXXX")
{
  printf '# Generated by scripts/generate-readme-assets.sh\n'
  printf '# Renderer: %s\n' "$observed_chromium_version"
  find Cargo.toml Cargo.lock src scripts/generate-readme-assets.sh \
    scripts/verify-readme-assets-container.sh scripts/readme-assets.Dockerfile \
    tests/fixtures/readme-assets -type f -print0 |
    LC_ALL=C sort -z |
    xargs -0 sha256sum
  for asset in "${assets[@]}"; do
    sha256sum "assets/$asset"
  done
} >"$manifest_tmp"
mv "$manifest_tmp" "$manifest"
verify_manifest
printf 'Regenerated and pinned README assets with %s.\n' "$observed_chromium_version"
